// 十神：以日主为我，(对方五行, 同异阴阳) -> 十神
function shiShen(dayGan, otherGan) {
  const meWx = GAN_WUXING[dayGan], meYy = GAN_YINYANG[dayGan];
  const otWx = GAN_WUXING[otherGan], otYy = GAN_YINYANG[otherGan];
  const same = meYy === otYy;
  if (otWx === meWx)        return same ? '比肩' : '劫财';
  if (SHENG[meWx] === otWx) return same ? '食神' : '伤官';
  if (KE[meWx]   === otWx)  return same ? '偏财' : '正财';
  if (KE[otWx]   === meWx)  return same ? '七杀' : '正官';
  if (SHENG[otWx] === meWx) return same ? '偏印' : '正印';
  return '?';
}

